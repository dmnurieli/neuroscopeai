"""Turns scripts/stages/recordings.jsonl (+ trainingdata.json) into
app/Sources/AirlineKit/GraduationRecordings.swift. Run with `python3 -I scripts/stages/to_swift.py`.
The newest line wins when a (stage, prompt) pair was recorded twice."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, "recordings.jsonl")
TD = os.path.join(HERE, "trainingdata.json")
DST = os.path.join(ROOT, "app/Sources/AirlineKit/GraduationRecordings.swift")


def lit(s: str) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif o < 0x20 or o == 0x7F or 0xD800 <= o <= 0xDFFF:
            out.append("\\u{%X}" % o)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main() -> None:
    rows = {}
    order = []
    with open(SRC, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            key = (r["stage"], r["prompt_id"])
            if key not in rows:
                order.append(key)
            rows[key] = r
    vocab_slots = {r["vocab_slots"] for r in rows.values()}
    vocab_entries = {r["vocab_entries"] for r in rows.values()}
    if len(vocab_slots) != 1 or len(vocab_entries) != 1:
        sys.exit(f"stages disagree on the vocabulary: {vocab_slots} {vocab_entries}")
    out = [
        "// GENERATED by scripts/stages/to_swift.py from scripts/stages/recordings.jsonl — do not hand-edit.",
        "// Every output below was produced on this Mac by the app's own engine (greedy, bf16 on Metal) from the",
        "// stage named in its repo/branch/commit; re-record with scripts/stages/record.sh.",
        "",
        "extension Graduation {",
        f"    public static let vocabSlots = {vocab_slots.pop()}",
        f"    public static let vocabEntries = {vocab_entries.pop()}",
        "",
        "    public static let recordings: [StageRecording] = [",
    ]
    for key in order:
        r = rows[key]
        picks = ", ".join(f"StagePick(token: {lit(p['token'])}, prob: {p['prob']:.6g})" for p in r["next_top"])
        out.append("        StageRecording(")
        out.append(f"            stage: {lit(r['stage'])}, label: {lit(r['label'])},")
        out.append(f"            repo: {lit(r['repo'])}, branch: {lit(r['branch'])}, commit: {lit(r['commit'])},")
        out.append(f"            trainedTokens: {int(r['trained_tokens'])}, promptID: {lit(r['prompt_id'])}, prompt: {lit(r['prompt'])},")
        out.append(f"            format: {lit(r['format'])}, maxTokens: {r['max_tokens']}, tokensGenerated: {r['tokens_generated']},")
        out.append(f"            stop: {lit(r['stop'])}, tokPerS: {r['tok_per_s']:.1f}, recordedAt: {lit(r['recorded_at'])}, device: {lit(r['device'])},")
        out.append(f"            nextTop: [{picks}],")
        out.append(f"            output: {lit(r['output'])}),")
    out.append("    ]")
    out.append("")
    if os.path.exists(TD):
        td = json.load(open(TD, encoding="utf-8"))
        out.append(f"    public static let trainingDataIndex: String? = {lit(td['index'])}")
        out.append(f"    public static let trainingDataQueriedAt: String? = {lit(td['queried_at'])}")
        out.append("    public static let trainingDataCounts: [String: Int] = [")
        for c in td["counts"]:
            out.append(f"        {lit(c['phrase'])}: {int(c['count'])},")
        out.append("    ]")
    else:
        out.append("    public static let trainingDataIndex: String? = nil")
        out.append("    public static let trainingDataQueriedAt: String? = nil")
        out.append("    public static let trainingDataCounts: [String: Int] = [:]")
    out.append("}")
    with open(DST, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {DST}: {len(order)} recordings")


main()
